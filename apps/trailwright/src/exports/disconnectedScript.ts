import type { Project } from '../model/schema';

// Target solution versions of disconnected operations by release (Learn: Deploy disconnected operations, Initialize each Azure Local node).
export const targetSolutionVersions: Record<string, string> = {
  '2604': '12.2604.1003.1005',
  '2605': '12.2605.1003.1003',
  '2606': '12.2606.1003.205',
  '2607': '12.2607.1003.73',
  '2608': '12.2608.1003.9',
  '2609': '12.2609.1003.7',
};

// The resource providers the operator subscription needs before the management cluster is deployed.
export const resourceProviders = [
  'Microsoft.EdgeArtifact',
  'Microsoft.HybridCompute',
  'Microsoft.GuestConfiguration',
  'Microsoft.HybridConnectivity',
  'Microsoft.AzureStackHCI',
  'Microsoft.Kubernetes',
  'Microsoft.KubernetesConfiguration',
  'Microsoft.ExtendedLocation',
  'Microsoft.ResourceConnector',
  'Microsoft.HybridContainerService',
  'Microsoft.KeyVault',
];

const q = (s: string): string => `'${s.replace(/'/g, "''")}'`;

// A PowerShell 7 script that runs the documented deployment steps with the values from the design. Passwords are parameters, never values.
export function buildDisconnectedScript(p: Project): string {
  const d = p.disconnected;
  const mgmtIntent = p.networking.intents.find((i) => i.traffic.includes('management'))?.name ?? 'ManagementComputeStorage';
  const version = targetSolutionVersions[p.release.version] ?? '';
  const ldapPort = d.ldaps ? 3269 : 3268;
  const L: string[] = [];
  L.push(
    '#Requires -Version 7.0',
    `# ${p.meta.name}: disconnected operations (${d.role} cluster), Azure Local ${p.release.version}.`,
    '# Generated by Azure Local Trailwright from Microsoft Learn: Deploy disconnected operations for Azure Local and the management cluster.',
    '# Run each phase where it says: Appliance on the first machine (seed node), NodeEnvironment on every node, ResourceProviders from a client,',
    '# NodeInit on every node (first machine first). Passwords are asked for as secure strings; nothing secret is stored in this file.',
    'param(',
    "  [Parameter(Mandatory)][ValidateSet('Appliance', 'NodeEnvironment', 'ResourceProviders', 'NodeInit')][string]$Phase,",
    '  [securestring]$IngressCertPassword,',
    '  [securestring]$ManagementCertPassword,',
    '  [securestring]$LdapPassword',
    ')',
    '',
    'Set-StrictMode -Version Latest',
    "$ErrorActionPreference = 'Stop'",
    '',
    `$applianceConfigBasePath = ${q(d.basePath)}`,
    `$applianceFQDN = ${q(d.domainSuffix)}`,
    `$applianceCloudName = 'azure.local'`,
    `$subscriptionName = ${q(d.operatorSubscriptionName)}`,
    `$resourceGroup = ${q(d.resourceGroup)}`,
    `$targetSolutionVersion = ${q(version)}`,
    '',
    'switch ($Phase) {',
    "  'Appliance' {",
    '    # Needs: the appliance files and OperationsModule in the base folder, and the certificates under certs\\IngressEndpointsCerts and certs\\ManagementEndpointsCerts.',
    '    if (-not $IngressCertPassword -or -not $ManagementCertPassword -or -not $LdapPassword) { throw "Provide -IngressCertPassword, -ManagementCertPassword and -LdapPassword." }',
    '    Import-Module "$applianceConfigBasePath\\OperationsModule\\Azure.Local.DisconnectedOperations.psd1" -Force',
    '    $certsPath = "$applianceConfigBasePath\\certs"',
    '    $mgmntCertFolderPath = "$certsPath\\ManagementEndpointsCerts"',
    '    $ingressCertFolderPath = "$certsPath\\IngressEndpointsCerts"',
    '',
    '    $managementNetworkConfiguration = New-ApplianceManagementNetworkConfiguration `',
    `      -ManagementIpAddress ${q(d.managementIp)} -ManagementIpv4PrefixLength ${d.managementPrefixLength} \``,
    '      -TlsCertificatePath "$mgmntCertFolderPath\\ManagementEndpointSsl.pfx" -TlsCertificatePassword $ManagementCertPassword `',
    '      -ClientCertificatePath "$mgmntCertFolderPath\\ManagementEndpointClientAuth.pfx" -ClientCertificatePassword $ManagementCertPassword',
    '',
    '    $ingressNetworkConfiguration = New-ApplianceIngressNetworkConfiguration `',
    `      -DnsServer ${q(d.dnsServer)} -IngressNetworkGateway ${q(d.ingressGateway)} -IngressIpAddress ${q(d.ingressIp)} \``,
    `      -IngressNetworkPrefixLength ${d.ingressPrefixLength} -ExternalDomainSuffix ${q(d.domainSuffix)}`,
    '',
    `    $oidcCertChain = Get-CertificateChainFromEndpoint -requestUri ${q(d.authority)}`,
    d.ldaps ? `    $ldapsCertChain = Get-CertificateChainFromEndpoint -requestUri ${q(`https://${d.ldapServer}`)}` : '    # LDAPS is off: LdapsCertChainInfo is omitted.',
    '    $identityParams = @{',
    `      Authority = ${q(d.authority)}`,
    `      ClientId = ${q(d.clientId)}`,
    `      RootOperatorUserPrincipalName = ${q(d.rootOperatorUpn)}`,
    `      LdapServer = ${q(d.ldapServer)}`,
    `      LdapPort = ${ldapPort}`,
    '      LdapCredential = New-Object PSCredential -ArgumentList @("ldap", $LdapPassword)',
    `      SyncGroupIdentifier = ${q(d.syncGroupIdentifier)}`,
    '      OidcCertChainInfo = $oidcCertChain',
    ...(d.ldaps ? ['      LdapsCertChainInfo = $ldapsCertChain'] : []),
    '    }',
    '    $identityConfiguration = New-ApplianceExternalIdentityConfiguration @identityParams',
    '    $CertificatesConfiguration = New-ApplianceCertificatesConfiguration -certificatesFolder $ingressCertFolderPath -certificatePassword $IngressCertPassword',
    '',
    `    $networkIntentName = ${q(mgmtIntent)}`,
    `    $TimeServers = ${q(d.timeServers)}`,
    '    $installAzureLocalParams = @{',
    '      Path = $applianceConfigBasePath',
    '      IngressNetworkConfiguration = $ingressNetworkConfiguration',
    '      ManagementNetworkConfiguration = $managementNetworkConfiguration',
    '      IngressSwitchName = "ConvergedSwitch($networkIntentName)"',
    '      ManagementSwitchName = "ConvergedSwitch($networkIntentName)"',
    '      ApplianceManifestFile = (Join-Path $applianceConfigBasePath AzureLocal.DisconnectedOperations.manifest.json)',
    '      IdentityConfiguration = $identityConfiguration',
    '      CertificatesConfiguration = $CertificatesConfiguration',
    '      ExternalTimeServers = $TimeServers',
    '    }',
    '    # Takes a few hours. Add -clean to start from scratch; omit -disconnectMachineDeploy for limited connectivity.',
    '    Install-Appliance @installAzureLocalParams -disconnectMachineDeploy -Verbose',
    '  }',
    "  'NodeEnvironment' {",
    '    # Teaches the node about the private cloud. On versions before 2607 use the legacy Add-AzEnvironment approach from the same article.',
    '    Add-AzLocalEnvironment -ArmEndpoint "https://armmanagement.$($applianceFQDN)"',
    '    Get-AzEnvironment | Where-Object Name -eq $applianceCloudName',
    '  }',
    "  'ResourceProviders' {",
    '    # Run from a client, not from an Azure Local node.',
    '    Connect-AzAccount -EnvironmentName $applianceCloudName -UseDeviceAuthentication',
    '    $subscription = Get-AzSubscription -SubscriptionName $subscriptionName',
    '    Set-AzContext -SubscriptionId $subscription.Id | Out-Null',
    `    foreach ($ns in @(${resourceProviders.map(q).join(', ')})) { Register-AzResourceProvider -ProviderNamespace $ns | Out-Null }`,
    '    Get-AzResourceProvider | Format-Table',
    '  }',
    "  'NodeInit' {",
    '    # Run on the first machine first, then on every other node.',
    '    Connect-AzAccount -EnvironmentName $applianceCloudName -UseDeviceAuthentication',
    '    $subscription = Get-AzSubscription -SubscriptionName $subscriptionName',
    '    Set-AzContext -SubscriptionId $subscription.Id | Out-Null',
    '    $armTokenResponse = Get-AzAccessToken -ResourceUrl "https://armmanagement.$($applianceFQDN)"',
    '    $ArmAccessToken = [System.Net.NetworkCredential]::new("", $armTokenResponse.Token).Password',
    '    Invoke-AzStackHciArcInitialization -SubscriptionID $subscription.Id -TenantID $subscription.TenantId -ResourceGroup $resourceGroup -Cloud $applianceCloudName -Region "Autonomous" -CloudFqdn $applianceFQDN -ArmAccessToken $ArmAccessToken -TargetSolutionVersion $targetSolutionVersion',
    '  }',
    '}',
    '',
    '# Then: pre-create the Azure Key Vault and wait five minutes; open https://portal.$applianceFQDN and deploy Azure Local from the nodes you initialized;',
    '# afterwards back up the BitLocker recovery keys and the host guardian service certificates, register the cluster, and lock down the management cluster.',
  );
  return `${L.join('\n')}\n`;
}
